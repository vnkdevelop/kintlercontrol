def big_code(code: str) -> str:
    if not code.isascii() or not code.isdigit() or len(code) != 6:
        raise ValueError("A six-digit connection code is required")
    rows = ["  ".join(DIGITS[digit][row] for digit in code) for row in range(5)]
    return "\n".join(line for row in rows for line in (row, row))
